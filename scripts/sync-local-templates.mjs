#!/usr/bin/env node
// Regenerates src/app/enrico-ceruti-violin/templates/local/generated-index.ts from whatever
// *.json files sit in that folder. Run via `npm run sync-local-templates`, or automatically
// before `npm start` — see package.json and templates/local/README.md.
//
// generated-index.ts never ships: the `production` fileReplacement in angular.json always
// substitutes empty-index.ts instead, regardless of what this script last wrote to disk or
// whether it ran at all — see empty-index.ts.
import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const localDir = path.join(scriptDir, '..', 'src/app/enrico-ceruti-violin/templates/local');
const outFile = path.join(localDir, 'generated-index.ts');

function toIdentifier(fileName, index) {
  const base = fileName.replace(/\.json$/i, '').replace(/[^a-zA-Z0-9]/g, '_');
  const ident = `raw_${index}_${base}`;
  return /^[0-9]/.test(ident) ? `_${ident}` : ident;
}

const jsonFiles = readdirSync(localDir, { withFileTypes: true })
  .filter(e => e.isFile() && e.name.toLowerCase().endsWith('.json'))
  .map(e => e.name)
  .sort();

const header = '// GENERATED by scripts/sync-local-templates.mjs — do not hand-edit.\n'
  + '// Regenerate with `npm run sync-local-templates`. See ../local/README.md.\n';

let body;
if (jsonFiles.length === 0) {
  body = "import { EnricoCerutiTemplate } from '../../ceruti-types';\n\n"
    + 'export const LOCAL_TEMPLATES: EnricoCerutiTemplate[] = [];\n';
} else {
  const idents = jsonFiles.map(toIdentifier);
  const imports = [
    "import { EnricoCerutiTemplate } from '../../ceruti-types';",
    "import { templateFromRecipeJson } from '../recipe-json';",
    ...jsonFiles.map((f, i) => `import ${idents[i]} from './${f}';`),
  ].join('\n');
  body = `${imports}\n\n`
    + `export const LOCAL_TEMPLATES: EnricoCerutiTemplate[] = [${idents.join(', ')}].map(templateFromRecipeJson);\n`;
}

writeFileSync(outFile, header + '\n' + body);
console.log(`sync-local-templates: ${jsonFiles.length} template(s) — ${jsonFiles.join(', ') || 'none'}`);
