/**
 * Converts a raw recipe object copied from session storage into an
 * EnricoCerutiTemplate. The session-storage JSON wraps the params under a
 * nested `params` key alongside top-level metadata fields (`key`, `label`,
 * `fileName`, `referenceImage`, `paths`, etc.).  Pass the pasted object
 * directly – no manual editing required.
 */
function templateFromRecipeJson(raw: any): EnricoCerutiTemplate {
  return {
    key: raw.key ?? '',
    label: raw.label ?? '',
    // `||`, not `??`: pasted recipe JSON has twice arrived carrying `"recipeName": ""`, which
    // `??` lets through. A blank name is not a name — it fails the identity check
    // loadMatchingStoredRecipe runs on every restore, so the design silently reverts to the
    // default template on refresh, and a file saved from it carries the blank on to disk. The
    // blobs below are all named correctly; this is the backstop for the next one pasted in.
    recipeName: raw.recipeName || 'enrico-ceruti-violin',
    fileName: raw.fileName ?? '',
    version: raw.version ?? RECIPE_SCHEMA_VERSION,
    description: raw.description ?? '',
    referenceImage: raw.referenceImage,
    referenceImages: raw.referenceImages,
    params: (raw.params ?? raw) as EnricoCerutiParams,
    paths: raw.paths ?? [],
  };
}

